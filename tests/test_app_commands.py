"""every command the app registers is listed for permissions and allowed for the app's own screens: one that is not is
refused at run time (read_progress was, so the first index showed a bar that never moved)"""
import json
import re
from pathlib import Path

APP = Path(__file__).resolve().parents[1] / "app" / "src-tauri"


def test_registered_commands_are_listed_and_allowed():
    lib = (APP / "src" / "lib.rs").read_text(encoding="utf-8")
    cmds = [c.strip() for c in re.search(r"generate_handler!\[(.*?)\]", lib, re.S).group(1).replace("\n", " ").split(",") if c.strip()]
    assert len(cmds) >= 10
    listed = set(re.findall(r'^\s+"([a-z_]+)",', (APP / "build.rs").read_text(encoding="utf-8"), re.M))
    allowed = set(json.loads((APP / "capabilities" / "default.json").read_text(encoding="utf-8"))["permissions"])
    for c in cmds:
        assert c in listed, f"{c}: not in build.rs"
        assert "allow-" + c.replace("_", "-") in allowed, f"{c}: not allowed in capabilities/default.json"
        assert (APP / "permissions" / "autogenerated" / f"{c}.toml").exists(), f"{c}: no permission file"


def test_the_search_page_may_only_open_files():
    page = json.loads((APP / "capabilities" / "search-page.json").read_text(encoding="utf-8"))
    assert page["permissions"] == ["allow-open-path"]
